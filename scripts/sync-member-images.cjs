const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const members = JSON.parse(fs.readFileSync(path.join(root, 'src/data/members.json'), 'utf8'));
const refs = new Set();
for (const team of members) for (const member of team.members) {
  refs.add(member.profileImageUrl);
  for (const slide of member.slides || []) if (slide.type === 'image') refs.add(slide.src);
  for (const image of member.brochureImages || []) refs.add(image);
}
const images = [...refs].sort();
const lines = ['// Generated by scripts/sync-member-images.cjs; do not edit manually.'];
images.forEach((image, i) => {
  if (!fs.existsSync(path.join(root, 'src', image))) throw new Error(`Missing member image: ${image}`);
  lines.push(`import image${i} from ${JSON.stringify('../' + image)};`);
});
lines.push('', 'const memberImages = {');
images.forEach((image, i) => lines.push(`  ${JSON.stringify(image)}: image${i},`));
lines.push('};', '', 'export default memberImages;', '');
const file = path.join(root, 'src/data/memberImages.js');
const content = lines.join('\n');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(file, 'utf8') !== content) throw new Error('Run node scripts/sync-member-images.cjs');
} else fs.writeFileSync(file, content);
